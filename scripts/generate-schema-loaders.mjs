/**
 * Emits dist/schema-loaders.generated.js: a map of specifier -> `() =>
 * import('literal')`. Bun compile only embeds string-literal imports, so this
 * is what actually packs `@elastic/schemas` into the binary.
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(fileURLToPath(import.meta.url), '..', '..')
const schemasRoot = join(root, 'node_modules', '@elastic', 'schemas')

const groups = [
  { dir: join(schemasRoot, 'src', 'es', 'json'), spec: '@elastic/schemas/es/json', json: true },
  { dir: join(schemasRoot, 'src', 'kibana', 'json'), spec: '@elastic/schemas/kibana/json', json: true },
  { dir: join(schemasRoot, 'src', 'cloud', 'json'), spec: '@elastic/schemas/cloud/json', json: true },
  { dir: join(schemasRoot, 'lib', 'es', 'tools', 'apis'), spec: '@elastic/schemas/es/tools/apis', json: false },
  { dir: join(schemasRoot, 'lib', 'kibana', 'tools', 'apis'), spec: '@elastic/schemas/kibana/tools/apis', json: false },
  { dir: join(schemasRoot, 'lib', 'cloud', 'tools', 'apis'), spec: '@elastic/schemas/cloud/tools/apis', json: false },
]

/** Schema filenames are dotted identifiers plus an extension, nothing else. */
export function isSafeSchemaFilename (file, suffix) {
  return typeof file === 'string' && file.endsWith(suffix) && /^[A-Za-z0-9._-]+$/.test(file)
}

/** Quote a package specifier for generated JS. Leaves `/` intact so bun can match the literal import. */
export function quoteSpecifier (spec) {
  return JSON.stringify(spec).replace(/[<>\u2028\u2029]/g, (ch) => {
    if (ch === '<') return '\\u003C'
    if (ch === '>') return '\\u003E'
    if (ch === '\u2028') return '\\u2028'
    return '\\u2029'
  })
}

export async function generateSchemaLoaders () {
  const lines = [
    '/*',
    ' * Copyright Elasticsearch B.V. and contributors',
    ' * SPDX-License-Identifier: Apache-2.0',
    ' */',
    '',
    '// Generated by scripts/generate-schema-loaders.mjs. Do not edit.',
    'export const schemaLoaders = {',
  ]

  let count = 0
  for (const group of groups) {
    const files = await readdir(group.dir)
    const suffix = group.json ? '.json' : '.js'
    for (const file of files) {
      if (!isSafeSchemaFilename(file, suffix)) continue
      const quoted = quoteSpecifier(`${group.spec}/${file}`)
      if (group.json) {
        lines.push(`  ${quoted}: () => import(${quoted}, { with: { type: 'json' } }),`)
      } else {
        lines.push(`  ${quoted}: () => import(${quoted}),`)
      }
      count++
    }
  }

  lines.push('}')
  lines.push('')

  const outDir = join(root, 'dist')
  await mkdir(outDir, { recursive: true })
  const out = join(outDir, 'schema-loaders.generated.js')
  await writeFile(out, lines.join('\n'))
  return { count, out }
}

const entry = process.argv[1]
if (entry != null && import.meta.url === pathToFileURL(resolve(entry)).href) {
  const { count, out } = await generateSchemaLoaders()
  process.stdout.write(`wrote ${count} schema loaders to ${out}\n`)
}
